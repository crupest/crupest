def face_text(face_id: object) -> str | None:
    """Return the bare ``faceText`` for an id, when the segment omitted it."""
    return FACE_TEXTS.get(str(face_id or ""))


def face_id(name: str) -> str | None:
    """Resolve a ``faceText``; accept it with or without a leading slash."""
    value = name.strip().lstrip("/")
    if not value:
        return None
    return FACE_IDS.get(value)
